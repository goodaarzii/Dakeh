package user

import (
	"context"
	"errors"
	"fmt"
	"strings"

	"github.com/google/uuid"

	"github.com/goodaarzii/dakeh/internal/domain"
)

// Repository is what this usecase needs from storage (implemented in repository/postgres).
type Repository interface {
	Create(ctx context.Context, u domain.User) (domain.User, error)
	GetByEmail(ctx context.Context, email string) (domain.User, error)
	GetByID(ctx context.Context, id uuid.UUID) (domain.User, error)
	UpdateLastLogin(ctx context.Context, id uuid.UUID) error
}

// PasswordHasher is implemented in internal/security.
type PasswordHasher interface {
	Hash(plain string) (string, error)
	Compare(hash, plain string) error
}

// TokenIssuer is implemented in internal/security (JWTIssuer).
type TokenIssuer interface {
	Issue(userID uuid.UUID, role domain.Role) (string, error)
}

// AuthResult is the outcome of register/login: a user plus a token.
// It lives here because it is a usecase result, not a business entity.
type AuthResult struct {
	User        domain.User
	AccessToken string
}

type Service struct {
	repo   Repository
	hasher PasswordHasher
	tokens TokenIssuer
}

func NewService(repo Repository, hasher PasswordHasher, tokens TokenIssuer) *Service {
	return &Service{repo: repo, hasher: hasher, tokens: tokens}
}

type RegisterInput struct {
	Email    string
	Phone    string
	Password string
	FullName string
}

func (s *Service) Register(ctx context.Context, in RegisterInput) (AuthResult, error) {
	hash, err := s.hasher.Hash(in.Password)
	if err != nil {
		return AuthResult{}, fmt.Errorf("hash password: %w", err)
	}

	u, err := s.repo.Create(ctx, domain.User{
		Email:        normalizeEmail(in.Email),
		Phone:        strings.TrimSpace(in.Phone),
		PasswordHash: hash,
		FullName:     strings.TrimSpace(in.FullName),
	})
	if err != nil {
		return AuthResult{}, err
	}

	// u.ID is the real ID generated by Postgres (it comes back from the INSERT).
	token, err := s.tokens.Issue(u.ID, u.Role)
	if err != nil {
		return AuthResult{}, fmt.Errorf("issue token: %w", err)
	}
	return AuthResult{User: u, AccessToken: token}, nil
}

// Login checks credentials and returns a token.
// Wrong email and wrong password return the same error on purpose.
func (s *Service) Login(ctx context.Context, email, password string) (AuthResult, error) {
	u, err := s.repo.GetByEmail(ctx, normalizeEmail(email))
	if errors.Is(err, domain.ErrNotFound) {
		return AuthResult{}, domain.ErrInvalidCredentials
	}
	if err != nil {
		return AuthResult{}, err
	}

	if err := s.hasher.Compare(u.PasswordHash, password); err != nil {
		return AuthResult{}, domain.ErrInvalidCredentials
	}
	if !u.IsActive {
		return AuthResult{}, domain.ErrUserInactive
	}

	if err := s.repo.UpdateLastLogin(ctx, u.ID); err != nil {
		return AuthResult{}, err
	}

	token, err := s.tokens.Issue(u.ID, u.Role)
	if err != nil {
		return AuthResult{}, fmt.Errorf("issue token: %w", err)
	}
	return AuthResult{User: u, AccessToken: token}, nil
}

func (s *Service) GetByID(ctx context.Context, id uuid.UUID) (domain.User, error) {
	return s.repo.GetByID(ctx, id)
}

func normalizeEmail(email string) string {
	return strings.ToLower(strings.TrimSpace(email))
}
