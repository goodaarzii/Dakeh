import { useEffect, useState, type FormEvent } from 'react'
import { Link, Outlet, useLocation, useNavigate, useSearchParams } from 'react-router-dom'
import { LOGO_IMAGE, SHOP_NAME } from '../config'
import { useAuth } from '../lib/auth'
import { useCart } from '../lib/cart'
import { inspector } from '../lib/inspector'
import { ApiInspector, InspectorButton } from './ApiInspector'
import { CartIcon, SearchIcon, UserIcon } from './icons'

function Header() {
  const { user, ready } = useAuth()
  const { cart } = useCart()
  const navigate = useNavigate()
  const location = useLocation()
  const [params] = useSearchParams()
  const [term, setTerm] = useState(params.get('q') ?? '')

  // Keep the search box in step with the address bar (back button, "clear filters").
  useEffect(() => {
    if (location.pathname === '/') setTerm(params.get('q') ?? '')
  }, [location.pathname, params])

  function onSubmit(e: FormEvent) {
    e.preventDefault()
    const q = term.trim()
    navigate(q ? `/?q=${encodeURIComponent(q)}` : '/')
  }

  const firstName = user?.full_name.split(' ')[0] ?? ''

  return (
    <header className="bg-ink text-paper">
      <div className="mx-auto flex h-16 max-w-[1200px] items-center gap-8 px-6">
        <Link to="/" className="flex items-center gap-2.5">
          <img src={LOGO_IMAGE} alt="" className="h-9 w-9" />
          <span className="font-display text-[1.7rem] font-bold leading-none" style={{ fontStretch: '85%' }}>
            {SHOP_NAME}
          </span>
        </Link>

        <form onSubmit={onSubmit} role="search" className="relative mx-auto w-full max-w-xl">
          <label htmlFor="shop-search" className="sr-only">
            Search products
          </label>
          <input
            id="shop-search"
            value={term}
            onChange={(e) => setTerm(e.target.value)}
            placeholder="Search products"
            className="w-full rounded-lg border-[1.5px] border-transparent bg-paper py-2 pl-4 pr-11 text-ink placeholder:text-ink/50 focus:border-mist focus:outline-none"
          />
          <button type="submit" className="absolute right-1.5 top-1/2 -translate-y-1/2 rounded-md p-1.5 text-ink hover:bg-mist/40" aria-label="Search">
            <SearchIcon />
          </button>
        </form>

        <nav className="flex items-center gap-5">
          {ready &&
            (user ? (
              <Link to="/account" className="flex items-center gap-2 font-semibold hover:text-sand">
                <UserIcon />
                {firstName}
              </Link>
            ) : (
              <>
                <Link to="/login" className="font-semibold hover:text-sand">
                  Log in
                </Link>
                <Link to="/register" className="btn btn-sm bg-sand !text-ink hover:bg-mist">
                  Create account
                </Link>
              </>
            ))}
          <Link to="/cart" className="relative flex items-center gap-2 font-semibold hover:text-sand" aria-label={`Cart, ${cart.itemCount} items`}>
            <CartIcon className="h-6 w-6" />
            {cart.itemCount > 0 && (
              <span className="absolute -right-3 -top-2 min-w-5 rounded-full bg-sand px-1.5 text-center text-xs font-bold text-ink">
                {cart.itemCount}
              </span>
            )}
          </Link>
        </nav>
      </div>
    </header>
  )
}

function Footer() {
  return (
    <footer className="mt-24 border-t-[1.5px] border-mist">
      <div className="mx-auto flex max-w-[1200px] items-start justify-between gap-10 px-6 py-10">
        <div className="max-w-xl">
          <p className="font-display text-2xl font-bold">{SHOP_NAME}</p>
          <p className="mt-2 text-ink/75">
            A test shop. The API is written in Go and keeps its data in Postgres, Redis and MinIO. This front end was generated by AI,
            and nothing here can be bought yet.
          </p>
        </div>
        <button type="button" onClick={() => inspector.setOpen(true)} className="btn btn-outline btn-sm shrink-0">
          Open the API inspector
        </button>
      </div>
    </footer>
  )
}

export default function Layout() {
  const { pathname } = useLocation()

  useEffect(() => {
    window.scrollTo(0, 0)
  }, [pathname])

  return (
    <>
      <Header />
      <div className="awning" aria-hidden="true" />
      <main className="mx-auto max-w-[1200px] px-6 pt-10">
        <Outlet />
      </main>
      <Footer />
      <InspectorButton />
      <ApiInspector />
    </>
  )
}
