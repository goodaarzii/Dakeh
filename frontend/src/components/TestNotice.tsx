import { useState } from 'react'
import { inspector } from '../lib/inspector'
import { CloseIcon } from './icons'

const KEY = 'dakeh.noticeDismissed'

export function TestNotice() {
  const [visible, setVisible] = useState(() => sessionStorage.getItem(KEY) !== '1')
  if (!visible) return null

  function dismiss() {
    sessionStorage.setItem(KEY, '1')
    setVisible(false)
  }

  return (
    <div className="mb-8 flex items-start justify-between gap-6 rounded-lg border-[1.5px] border-ink bg-paper px-5 py-4">
      <div>
        <p>
          <strong className="font-display text-lg">Dakeh is a test shop.</strong> Its API is written in Go, and this front end was
          generated by AI. Nothing here can be bought yet.
        </p>
        <button
          type="button"
          onClick={() => inspector.setOpen(true)}
          className="mt-2 font-semibold underline underline-offset-4 hover:text-steel"
        >
          See the requests behind this page
        </button>
      </div>
      <button type="button" onClick={dismiss} className="btn btn-quiet btn-sm -mr-2 -mt-1" aria-label="Dismiss this notice">
        <CloseIcon className="h-5 w-5" />
      </button>
    </div>
  )
}
